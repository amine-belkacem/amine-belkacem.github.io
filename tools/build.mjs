// Build step for the site (run after editing js/data.js, js/app.js or js/src/scene.js, before publishing):
//   npm install        (once)
//   npm run build
// 1. bundles js/src/scene.js + three.js into one minified file, js/scene.min.js
// 2. pre-renders the hero text (English + French) into index.html, so it paints before any script runs
// 3. writes the "last updated" date into js/meta.js (keeps the Lighthouse scores already there)
import { build } from "esbuild";
import puppeteer from "puppeteer-core";
import handler from "serve-handler";
import http from "node:http";
import { readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const chromePath = process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe";

/* 1. 3D bundle */
await build({
  entryPoints: [join(root, "js/src/scene.js")],
  outfile: join(root, "js/scene.min.js"),
  bundle: true, minify: true, format: "esm", target: "es2020",
  legalComments: "none",
  banner: { js: "/* MAB-26 hero scene. Bundles three.js r160 (MIT License, Copyright 2010-2023 three.js authors). */" },
});
console.log(`js/scene.min.js  ${Math.round(statSync(join(root, "js/scene.min.js")).size / 1024)} KB`);

/* 2. hero pre-render: ask the real page to render itself, in each language, and copy the result into index.html */
const server = http.createServer((req, res) => handler(req, res, { public: root }));
await new Promise((r) => server.listen(8798, r));
const browser = await puppeteer.launch({ executablePath: chromePath, headless: true });
const parts = [];
for (const lang of ["en", "fr"]) {
  const page = await browser.newPage();
  await page.goto(`http://localhost:8798/?prerender=1&lang=${lang}`, { waitUntil: "domcontentloaded" });
  // wait until app.js has redrawn the hero (the old pre-rendered copies are gone)
  await page.waitForFunction(() => document.querySelector("#heroInner .name") && !document.querySelector("#heroInner .pre"));
  // ids are dropped: two copies (en + fr) live in the page until app.js redraws the hero
  const html = (await page.$eval("#heroInner", (el) => el.innerHTML.trim())).replace(/ id="[^"]*"/g, "");
  parts.push(`<div class="pre" data-l="${lang}">${html}</div>`);
  await page.close();
}
await browser.close();
server.close();
const indexPath = join(root, "index.html");
const index = readFileSync(indexPath, "utf8");
const marked = /<!--hero:start-->[\s\S]*?<!--hero:end-->/;
if (!marked.test(index)) throw new Error("index.html: hero markers not found");
writeFileSync(indexPath, index.replace(marked, `<!--hero:start-->\n${parts.join("\n")}\n<!--hero:end-->`));
console.log("index.html       hero pre-rendered (en + fr)");

/* 3. meta */
const metaPath = join(root, "js/meta.js");
let meta = {};
if (existsSync(metaPath)) {
  const m = readFileSync(metaPath, "utf8").match(/window\.SITE\s*=\s*(\{[\s\S]*\});/);
  if (m) meta = JSON.parse(m[1]);
}
meta.updated = new Date().toISOString().slice(0, 10);
writeFileSync(metaPath, `/* Generated by tools/build.mjs and tools/lighthouse.mjs. Do not edit by hand. */\nwindow.SITE = ${JSON.stringify(meta, null, 2)};\n`);
console.log(`js/meta.js       updated ${meta.updated}`);

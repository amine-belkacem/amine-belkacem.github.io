// Measures the site with Lighthouse (phone and desktop) and stores the phone scores in js/meta.js for the footer.
//   npm run lighthouse                       -> serves this folder with gzip (like GitHub Pages) and measures it
//   npm run lighthouse -- https://amine-belkacem.github.io/   -> measures the live site instead
// Needs Google Chrome. Prints every category and the main timings.
import lighthouse from "lighthouse";
import * as chromeLauncher from "chrome-launcher";
import handler from "serve-handler";
import compression from "compression";
import http from "node:http";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
let url = process.argv[2];
let server = null;
if (!url) {
  const gzip = compression();
  server = http.createServer((req, res) => gzip(req, res, () => handler(req, res, { public: root })));
  await new Promise((r) => server.listen(8799, r));
  url = "http://localhost:8799/";
}

const chrome = await chromeLauncher.launch({ chromeFlags: ["--headless=new"] });
const results = {};
for (const form of ["mobile", "desktop"]) {
  const config = form === "desktop" ? (await import("lighthouse/core/config/desktop-config.js")).default : undefined;
  const r = await lighthouse(url, { port: chrome.port, output: "json", logLevel: "error" }, config);
  const c = r.lhr.categories, a = r.lhr.audits;
  results[form] = Object.fromEntries(Object.entries(c).map(([k, v]) => [k, Math.round(v.score * 100)]));
  console.log(`${form.padEnd(8)} ${Object.entries(results[form]).map(([k, v]) => `${k} ${v}`).join(" | ")}`);
  for (const k of ["first-contentful-paint", "largest-contentful-paint", "total-blocking-time", "cumulative-layout-shift", "speed-index", "total-byte-weight"]) console.log(`         ${k}: ${a[k].displayValue}`);
  if (form === "mobile") writeFileSync(join(root, "tools", ".last-lighthouse-mobile.json"), JSON.stringify(r.lhr));
}
await chrome.kill();
if (server) server.close();

const metaPath = join(root, "js/meta.js");
let meta = {};
if (existsSync(metaPath)) {
  const m = readFileSync(metaPath, "utf8").match(/window\.SITE\s*=\s*(\{[\s\S]*\});/);
  if (m) meta = JSON.parse(m[1]);
}
meta.lighthouse = { date: new Date().toISOString().slice(0, 10), url, mobile: results.mobile, desktop: results.desktop };
writeFileSync(metaPath, `/* Generated by tools/build.mjs and tools/lighthouse.mjs. Do not edit by hand. */\nwindow.SITE = ${JSON.stringify(meta, null, 2)};\n`);
console.log("scores written to js/meta.js");
